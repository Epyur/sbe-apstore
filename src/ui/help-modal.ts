/** Модалка «Справка»: подробная инструкция по работе с системой. */
export class HelpModal extends Modal {
  constructor(app: App) {
    super(app);
    this.modalEl.addClass('tn-apstore-help-modal');
  }

  onOpen(): void {
    this.titleEl.setText('Справка по системе');
    const wrap = this.contentEl.createDiv({ cls: 'tn-apstore-help' });
    for (const section of HELP_SECTIONS) {
      const card = wrap.createDiv({ cls: 'tn-card' });
      card.createDiv({ cls: 'tn-card-head' }).createEl('h3', { text: section.title });
      for (const p of section.body) {
        card.createDiv({ cls: 'tn-apstore-help-text', text: p });
      }
    }
  }

  onClose(): void {
    this.contentEl.empty();
  }
}
